"""Build an already generated Dragonfyre/Horizon workspace (no launcher changes).

This does not apply mixins or alter saves/profiles. Build logs/receipts and copied
binary go next to the selected applied/ source tree. Cached Cargo dependencies
are reused to limit disk/RAM usage on an 8-GB laptop.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def path(text: str) -> Path:
    return Path(text).expanduser().resolve()


def sha256(file: Path) -> str:
    hash_value = hashlib.sha256()
    with file.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            hash_value.update(chunk)
    return hash_value.hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--applied", type=path, required=True,
                        help="New isolated .../dragonfyre-native-*/applied generated by apply-dragonfyre-native.py")
    parser.add_argument("--rust-bin", type=path, help="Directory containing cargo.exe and rustc.exe")
    parser.add_argument("--mingw-bin", type=path, help="Directory containing gcc.exe, e.g. C:/msys64/mingw64/bin")
    parser.add_argument("--cargo-home", type=path, default=(ROOT / "work" / "native-cargo").resolve(),
                        help="Prepared offline Cargo registry/cache directory")
    parser.add_argument("--target-dir", type=path, default=(ROOT / "work" / "native-game-target").resolve(),
                        help="Existing reusable Cargo build cache; may be large")
    parser.add_argument("--profile", choices=("debug", "release"), default="debug")
    parser.add_argument("--features", default="", help="Explicit comma-separated features, e.g. audio")
    parser.add_argument("--cargo-config", type=path, help="Optional known Cargo config for link overrides")
    parser.add_argument("--dry-run", action="store_true", help="Validate and print the command without building")
    args = parser.parse_args()

    applied = args.applied
    run = applied.parent
    report = run / "apply-report.json"
    manifest = applied / "Cargo.toml"
    if applied.name != "applied" or not run.name.startswith("dragonfyre-native-"):
        parser.error("--applied must point to an isolated dragonfyre-native-*/applied directory")
    if not manifest.is_file():
        parser.error(f"Generated Horizon Cargo.toml not found: {manifest}")
    if not report.is_file():
        parser.error(f"Missing successful mixin receipt: {report}")
    try:
        apply_info = json.loads(report.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        parser.error(f"Could not read apply-report.json: {exc}")
    if apply_info.get("status") != "ok":
        parser.error(f"Mixin receipt is not PASS: {report}")
    if Path(apply_info.get("applied", "")).resolve() != applied:
        parser.error("Receipt points to a different generated directory")
    if not args.cargo_home.is_dir():
        parser.error(f"Offline Cargo cache is unavailable: {args.cargo_home}")
    if args.cargo_config and not args.cargo_config.is_file():
        parser.error(f"Cargo config not found: {args.cargo_config}")

    env = os.environ.copy()
    for directory, role in ((args.rust_bin, "Rust"), (args.mingw_bin, "MinGW")):
        if directory:
            if not directory.is_dir():
                parser.error(f"{role} directory not found: {directory}")
            env["PATH"] = str(directory) + os.pathsep + env.get("PATH", "")

    cargo_name = "cargo.exe" if os.name == "nt" else "cargo"
    cargo_found = shutil.which(cargo_name, path=env.get("PATH"))
    if cargo_found is None:
        parser.error("cargo executable not found. Pass --rust-bin.")
    cargo = Path(cargo_found).resolve()
    if args.mingw_bin:
        linker = args.mingw_bin / ("gcc.exe" if os.name == "nt" else "gcc")
        if not linker.is_file():
            parser.error(f"GNU linker not found: {linker}")
        env["CARGO_TARGET_X86_64_PC_WINDOWS_GNU_LINKER"] = str(linker)

    # No new target cache: reuses existing artifacts. It may change contents of
    # target-dir; do not use a user save/profile or a source directory for it.
    args.target_dir.mkdir(parents=True, exist_ok=True)
    env.update(
        CARGO_HOME=str(args.cargo_home),
        CARGO_TARGET_DIR=str(args.target_dir),
        CARGO_NET_OFFLINE="true",
        CARGO_INCREMENTAL="0",
        CARGO_BUILD_JOBS="1",
        CARGO_PROFILE_DEV_DEBUG="0",
        CARGO_PROFILE_DEV_OPT_LEVEL="0",
    )
    command = [
        str(cargo), "build", "--manifest-path", str(manifest),
        "--locked", "--offline", "-p", "horizon-client",
        "--no-default-features", "--jobs", "1",
    ]
    if args.profile == "release":
        command.append("--release")
    if args.features:
        command.extend(("--features", args.features))
    if args.cargo_config:
        command.extend(("--config", str(args.cargo_config)))

    log = run / f"build-{args.profile}.log"
    report_path = run / f"build-{args.profile}.json"
    output_binary = run / ("horizon-client-release.exe" if args.profile == "release" else "horizon-client-debug.exe")
    receipt = {
        "status": "not_started",
        "command": command,
        "applied": str(applied),
        "cargo": str(cargo),
        "cargo_home": str(args.cargo_home),
        "cargo_target_dir": str(args.target_dir),
        "profile": args.profile,
        "features": args.features,
        "mixin_receipt": str(report),
        "build_log": str(log),
    }
    print(f"Generated source: {applied}", flush=True)
    print(f"Cargo cache: {args.cargo_home}", flush=True)
    print(f"Reusable target: {args.target_dir}", flush=True)
    print(f"Build log: {log}", flush=True)
    print(f"Command: {' '.join(command)}", flush=True)
    if args.dry_run:
        print("DRY RUN: no build started", flush=True)
        return 0

    # Stream all compiler output into log; echo concise progress and errors.
    with log.open("w", encoding="utf-8", errors="replace") as handle:
        process = subprocess.Popen(
            command, cwd=applied, env=env,
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, encoding="utf-8", errors="replace",
            bufsize=1,
        )
        assert process.stdout is not None
        for line in process.stdout:
            handle.write(line)
            if line.lstrip().startswith(("Compiling ", "Checking ", "Finished ", "error:", "error[", "warning:")):
                print(line.rstrip(), flush=True)
        code = process.wait()
    receipt["exit_code"] = code
    if code != 0:
        receipt["status"] = "failed"
        report_path.write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
        print(f"FAIL: Cargo exited with {code}. See {log}", file=sys.stderr)
        return code

    compiled = args.target_dir / ("release" if args.profile == "release" else "debug") / (
        "horizon-client.exe" if os.name == "nt" else "horizon-client"
    )
    if not compiled.is_file():
        receipt["status"] = "missing_binary"
        report_path.write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
        print(f"FAIL: Cargo returned success but output missing: {compiled}", file=sys.stderr)
        return 1
    shutil.copy2(compiled, output_binary)
    receipt["status"] = "ok"
    receipt["binary"] = str(output_binary)
    receipt["sha256"] = sha256(output_binary)
    receipt["bytes"] = output_binary.stat().st_size
    report_path.write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
    print(f"PASS: Horizon native client compiled. Output: {output_binary}", flush=True)
    print(f"SHA-256: {receipt['sha256']}", flush=True)
    print("Not yet launched through Horizon Offline Launcher; gameplay, sound and Stage 10 remain unverified.", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
